@Composable
fun MhguTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColors
        else -> LightColors
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = MhguTypography,
        shapes = MhguShapes,
        content = content,
    )
}

@Preview(name = "Theme palette", showBackground = true)
@Composable
private fun ThemePalettePreview() {
    MhguTheme(dynamicColor = false) {
        Surface {
            Column(
                modifier = Modifier.fillMaxWidth().padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(12.dp),
            ) {
                Text("MHGU Codex", style = MaterialTheme.typography.headlineMedium)
                Text(
                    "Static palette fallback used before Android 12 or when dynamic color is off.",
                    style = MaterialTheme.typography.bodyMedium,
                )
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    listOf(
                        MaterialTheme.colorScheme.primary,
                        MaterialTheme.colorScheme.secondary,
                        MaterialTheme.colorScheme.tertiary,
                        MaterialTheme.colorScheme.error,
                    ).forEach { color ->
                        Swatch(color)
                    }
                }
            }
        }
    }
}

@Composable
private fun Swatch(color: Color) {
    androidx.compose.foundation.layout.Box(
        modifier = Modifier
            .size(40.dp)
            .background(color, CircleShape),
    )
}
